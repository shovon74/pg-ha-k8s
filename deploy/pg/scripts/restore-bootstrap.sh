#!/bin/sh
# Patroni custom bootstrap for a restored cluster (ADR-010, deploy/restore). Runs once, on the first member,
# in an empty volume. $1 is the recovery target time with a timezone offset, or empty for the latest state;
# $2 the target timeline (default latest).
# pgBackRest chooses the backup set (the newest one that ends before the target) and restores it. The
# recovery settings it writes to postgresql.auto.conf are then removed, because Patroni writes its own
# from bootstrap.pgbackrest.recovery_conf, and settings left in postgresql.auto.conf would be copied to
# every replica and would survive the end of recovery.
set -eu
PGDATA=/data/pgdata
mkdir -p "$PGDATA"; chmod 0700 "$PGDATA"
TL=${2:-latest}
if [ -n "${1:-}" ]; then
  set -- --type=time "--target=$1" "--target-timeline=$TL"
else
  set -- --type=default "--target-timeline=$TL"
fi
pgbackrest --stanza=main --log-level-console=info --log-level-file=off "$@" restore
sed -i '/^# Recovery settings generated by pgBackRest/d; /^restore_command/d; /^recovery_target/d' "$PGDATA/postgresql.auto.conf"
echo "restore-bootstrap: restore done, recovery is driven by Patroni's recovery_conf"
