#!/usr/bin/env bash
# L7 clean run: rebuild from scratch and regenerate every evidence file with make.
# Each target runs once; a failure is retried once, then recorded and the run continues (two-strikes rule).
# Logs go to .run/l7/, the result table to docs/evidence/L7-clean-run.md.
# Usage: scripts/l7-clean-run.sh
#        FROM=<step label> scripts/l7-clean-run.sh   resume at that step, keeping the rows already recorded
set -uo pipefail
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"
LOG_DIR="$ROOT_DIR/.run/l7"
OUT="$ROOT_DIR/docs/evidence/L7-clean-run.md"
mkdir -p "$LOG_DIR"
ROWS="$LOG_DIR/rows.tsv"
FROM=${FROM:-}
[ -n "$FROM" ] || : > "$ROWS"

now() { date -u +%H:%M:%S; }

# run <label> <make args...>
run() {
  local label=$1; shift
  local attempt start end rc
  if [ -n "$FROM" ]; then
    [ "$label" = "$FROM" ] || { printf '[%s] SKIP  %s (resuming at %s)\n' "$(now)" "$label" "$FROM"; return 0; }
    FROM=""; printf '[%s] RESUME at %s\n' "$(now)" "$label"
  fi
  for attempt in 1 2; do
    start=$(date +%s)
    printf '[%s] START %s (attempt %d): make %s\n' "$(now)" "$label" "$attempt" "$*"
    make "$@" > "$LOG_DIR/$label.$attempt.log" 2>&1; rc=$?
    end=$(date +%s)
    printf '[%s] END   %s rc=%d (%ds)\n' "$(now)" "$label" "$rc" "$((end - start))"
    if [ "$rc" -eq 0 ]; then
      printf '%s\t%s\tPASS\t%d\t%d\n' "$label" "make $*" "$attempt" "$((end - start))" >> "$ROWS"
      return 0
    fi
  done
  printf '%s\t%s\tFAIL\t2\t%d\n' "$label" "make $*" "$((end - start))" >> "$ROWS"
  return 1
}

STARTED=$(cat "$LOG_DIR/started" 2>/dev/null || true)
[ -n "${FROM:-}" ] && [ -n "$STARTED" ] || { STARTED=$(date -u '+%Y-%m-%d %H:%M:%S UTC'); echo "$STARTED" > "$LOG_DIR/started"; }
printf '[%s] L7 clean run started\n' "$(now)"

# Pre-step (skipped on resume): the three backup Jobs that failed in the L6 connectivity race (L6-security-history.md).
if [ -z "$FROM" ] && [ -f .run/kubeconfig ]; then
  KUBECONFIG=.run/kubeconfig bin/kubectl -n pg-ha delete job --ignore-not-found \
    pg-backup-29927280 pg-backup-manual-20261125172539 pg-backup-manual-20261125172613 \
    > "$LOG_DIR/00-delete-failed-jobs.log" 2>&1
fi

run 01-secrets secrets
run 02-down down
run 03-up up || { printf '[%s] make up failed twice, stopping\n' "$(now)"; BOOT_FAIL=1; }
if [ -z "${BOOT_FAIL:-}" ]; then
  run 04-seed seed
  # 04-seed-fixed exists because of the L7 resume: seed failed twice on the NetworkPolicy admission race, and
  # scripts/seed.sh got the same pg_isready wait as the backup Job. See L7-clean-run.md.
  [ "$FROM" != 04-seed-fixed ] || run 04-seed-fixed seed
  run 05-replication test-replication
  run 06-failover-pod failover-pod RUNS=3
  run 07-failover-node failover-node RUNS=3
  run 08-failover-storage failover-storage RUNS=3
  run 09-split-brain test-split-brain RUNS=3
  run 10-switchover switchover RUNS=3
  run 11-chain-1 failover-chain
  run 12-diverge-1 failover-diverge
  run 13-backup test-backup
  run 14-restore-full test-restore-full
  run 15-pitr test-pitr
  run 16-test-restore test-restore
  run 17-restore-schedule test-restore-schedule
  run 18-alerts test-alerts
  run 19-metrics test-metrics
  run 20-alerts-failover alerts-failover
  run 21-alerts-archive alerts-archive
  run 22-security test-security
  # Compound modes repeated last so they cannot delay the rest; each run overwrites its evidence file,
  # every run's log stays in .run/l7/.
  run 23-chain-2 failover-chain
  run 24-diverge-2 failover-diverge
  run 25-chain-3 failover-chain
  run 26-diverge-3 failover-diverge
  run 27-restore-clean restore-clean
fi
FINISHED=$(date -u '+%Y-%m-%d %H:%M:%S UTC')

{
  printf '# L7 clean run\n\n'
  printf 'Generated by `scripts/l7-clean-run.sh`. Started %s, finished %s.\n\n' "$STARTED" "$FINISHED"
  printf 'Sequence: delete the three failed L6 backup Jobs, `make secrets`, `make down`, `make up`, `make seed`, then every test target. A failed target is retried once; a second failure is recorded here and in `docs/known-limitations.md`, and the run continues.\n\n'
  printf '| Step | Command | Result | Attempts | Last attempt (s) |\n|---|---|---|---:|---:|\n'
  awk -F'\t' '{printf "| %s | `%s` | %s | %s | %s |\n", $1, $2, $3, $4, $5}' "$ROWS"
  printf '\nPer-target evidence: `L1-replication.md`, `L2-failover.md`, `L3-backup.md`, `L4-restore.md`, `L5-monitoring.md`, `L6-security.md` and their subdirectories. Raw logs are in `.run/l7/` (not committed).\n'
} > "$OUT"
printf '[%s] L7 clean run finished, table in %s\n' "$(now)" "$OUT"
