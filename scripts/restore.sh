#!/usr/bin/env bash
# L4 (ADR-010, R5.1, R5.3): restores the whole cluster from the pgBackRest repository into an empty namespace,
# through Patroni's custom bootstrap (deploy/restore). The first member restores and recovers, the other two
# clone from it, so the result is 1 primary and 2 streaming replicas, as in production.
#   NS=pg-restore              target namespace. The L0 certificates cover only pg-ha and pg-restore.
#   TARGET_TIME='YYYY-MM-DD HH:MM:SS+06'   point in time, with a REQUIRED timezone offset. Empty: latest.
#   TARGET_TIMELINE=latest     recovery target timeline (default latest).
# The restored cluster never archives into the source stanza: archive_mode is off (30-restore.yml), and it
# reads the repository only through restore_command. Never prints a secret.
. "$(dirname "$0")/lib.sh"
SRC_NS=$PG_NS; NS=${NS:-pg-restore}; TARGET_TIME=${TARGET_TIME:-}; TARGET_TIMELINE=${TARGET_TIMELINE:-latest}
[ "$NS" != "$SRC_NS" ] || die "refusing to restore into the source namespace $SRC_NS"
[ "$NS" = pg-restore ] || die "NS must be pg-restore: the L0 certificates name only pg-ha and pg-restore"
if [ -n "$TARGET_TIME" ]; then
  [[ "$TARGET_TIME" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}\ [0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]+)?[+-][0-9]{2}(:?[0-9]{2})?$ ]] ||
    die "TARGET_TIME must look like '2026-11-26 01:30:00+06', with a timezone offset (the VM runs UTC, the lead works in UTC+6)"
fi
[[ "$TARGET_TIMELINE" =~ ^(latest|current|[0-9]+)$ ]] || die "TARGET_TIMELINE must be latest, current or a number"
if kubectl get ns "$NS" >/dev/null 2>&1; then
  [ -z "$(kubectl -n "$NS" get pods,pvc -o name 2>/dev/null)" ] || die "namespace $NS is not empty, run: make restore-clean"
fi
T0=$(date +%s.%N)
log "Restoring into namespace $NS: target ${TARGET_TIME:-latest (end of the archive)}, timeline $TARGET_TIMELINE"

kubectl create ns "$NS" --dry-run=client -o yaml | kubectl apply -f - >/dev/null
# Same Secrets as the source namespace, copied server-side so no value is printed or stored in an annotation.
for s in pg-credentials pg-tls pgbackrest-tls pgbackrest-repo; do
  kubectl -n "$SRC_NS" get secret "$s" -o json | jq --arg s "$s" '{apiVersion, kind, type, data, metadata: {name: $s}}' |
    kubectl -n "$NS" apply --server-side --field-manager=pg-ha-restore --force-conflicts -f - >/dev/null
done

# 30-restore.yml: Patroni custom bootstrap through pgBackRest, merged over 10-base.yml and 20-archive.yml.
q() { printf "'%s'" "$1"; }
{ echo "# Generated by scripts/restore.sh at $(date -u +%FT%TZ). Do not edit or commit."
  echo "bootstrap:"
  echo "  method: pgbackrest"
  echo "  pgbackrest:"
  echo "    command: \"sh /etc/patroni/scripts/restore-bootstrap.sh $(q "$TARGET_TIME") $(q "$TARGET_TIMELINE")\""
  echo "    no_params: true"
  echo "    recovery_conf:"
  echo "      restore_command: pgbackrest --stanza=main archive-get %f \"%p\""
  echo "      recovery_target_timeline: $(q "$TARGET_TIMELINE")"
  echo "      recovery_target_action: promote"
  [ -z "$TARGET_TIME" ] || echo "      recovery_target_time: $(q "$TARGET_TIME")"
  echo "postgresql:"
  echo "  parameters:"
  echo "    archive_mode: \"off\"   # ADR-010: never archive into the source stanza"
} > "$ROOT_DIR/deploy/restore/30-restore.yml"
kubectl kustomize "$ROOT_DIR/deploy/restore" | sed "s|__PG_IMAGE__|$PG_IMAGE|; s|__POSTGRES_EXPORTER_IMAGE__|$POSTGRES_EXPORTER_IMAGE|" | kubectl apply -f - >/dev/null

PG_NS=$NS   # the Patroni helpers below now read the restored cluster
end=$((SECONDS + ${RESTORE_WAIT:-1200})); T_LEADER=""
until [ -n "$T_LEADER" ] && patroni_healthy; do
  [ $SECONDS -lt $end ] || { patroni_cluster | jq -r '.members[] | "\(.name) \(.role) \(.state)"' || true; die "restored cluster not healthy after ${RESTORE_WAIT:-1200} s"; }
  [ -n "$T_LEADER" ] || ! patroni_cluster 2>/dev/null | jq -e '[.members[] | select(.role == "leader" and .state == "running")] | length == 1' >/dev/null || T_LEADER=$(date +%s.%N)
  sleep 2
done
T1=$(date +%s.%N)
patroni_cluster | jq -r '.members[] | "  \(.name) \(.role) \(.state) timeline \(.timeline // "-")"'
log "RESTORE_OK namespace=$NS target=${TARGET_TIME:-latest} primary_ready=$(awk -v a="$T0" -v b="$T_LEADER" 'BEGIN{printf "%.1f", b-a}')s cluster_healthy=$(awk -v a="$T0" -v b="$T1" 'BEGIN{printf "%.1f", b-a}')s"
